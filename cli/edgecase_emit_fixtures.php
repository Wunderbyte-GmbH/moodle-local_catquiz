/**
 * Exports a value using short array syntax with no trailing whitespace.
 *
 * @param mixed $value
 * @param int $indent
 * @return string
 */
function edgecase_export_short($value, int $indent = 8): string {
    if (is_array($value)) {
        $pad = str_repeat(' ', $indent);
        $inner = str_repeat(' ', $indent + 4);
        $islist = array_keys($value) === range(0, count($value) - 1);
        $lines = [];
        foreach ($value as $k => $v) {
            $prefix = $islist ? '' : var_export((string) $k, true) . ' => ';
            $lines[] = $inner . $prefix . edgecase_export_short($v, $indent + 4);
        }
        return "[\n" . implode(",\n", $lines) . ",\n" . $pad . ']';
    }
    if (is_null($value)) {
        return 'null';
    }
    if (is_bool($value)) {
        return $value ? 'true' : 'false';
    }
    if (is_string($value)) {
        return var_export($value, true);
    }
    return (string) $value;
}

