/**
 * Immutable edge-case fixtures for IP estimation on pathological geometries.
 *
 * Each fixture persists seed, generator parameters, the materialised responses
 * (as [ability, response] pairs) and the expected identifiability class, so the
 * regression data survives changes to the RNG, generator or model. Generated by
 * cli/edgecase_emit_fixtures.php. Do not edit by hand.
 *
 * Expectation classes: F (unique finite optimum), B (boundary optimum),
 * W (weakly identified / flat likelihood), N (no unique finite maximum).
 *
 * @package    local_catquiz
 * @copyright  2026 Wunderbyte GmbH <info@wunderbyte.at>
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */

defined('MOODLE_INTERNAL') || die();

return [

HDR;

$out = $header;
foreach (edgecase_catalog() as $case) {
    $model = model_model::get_instance($case['model']);
    $responses = edgecase_build_responses($model, $case);
    $pairs = [];
    foreach ($responses as $r) {
        $pairs[] = '[' . round($r->get_personparams()->get_ability(), 6) . ', '
            . rtrim(rtrim(sprintf('%.4f', $r->get_response()), '0'), '.') . ']';
    }
    $gen = edgecase_export_short($case['generator'], 8);
    $out .= "    '{$case['id']}' => [\n";
    $out .= "        'id' => '{$case['id']}',\n";
    $out .= "        'model' => '{$case['model']}',\n";
    $out .= "        'estimation' => '{$case['estimation']}',\n";
    $out .= "        'class' => '{$case['class']}',\n";
    $out .= "        'seed' => {$case['seed']},\n";
    $out .= "        'expected' => '{$case['expected']}',\n";
    $out .= "        'generator' => {$gen},\n";
    $out .= "        'responses' => [\n";
    foreach ($pairs as $pair) {
        $out .= "            {$pair},\n";
    }
    $out .= "        ],\n";
    $out .= "    ],\n";
}
$out .= "];\n";

file_put_contents(__DIR__ . '/../tests/fixtures/edgecase_ip_fixtures.php', $out);
echo 'Fixtures written (' . number_format(strlen($out)) . " bytes, "
    . count(edgecase_catalog()) . " fixtures)\n";
